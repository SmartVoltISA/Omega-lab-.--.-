"""Ω-MEM-9 graph-dynamics pilot.

The future transition is generated by graph dynamics, not by a direct
memory->future lookup. Different histories converge to the same observable
node. Memory stores only the preceding graph node. A graph transition uses
(current node, previous node) as its local state; no future label is stored.
"""
from collections import Counter, defaultdict
import math, random

SEEDS = range(30)
N = 80000

# Directed graph. A and B converge to S1; S1 converges to S2.
# At S2, the predecessor edge determines which outgoing branch is active.
GRAPH = {
    "A": ["S1"], "B": ["S1"], "C": ["S1"],
    "S1": ["S2"],
    "S2": ["X", "Y"],
}


def entropy(c):
    n = sum(c.values())
    return 0.0 if not n else -sum((v/n)*math.log2(v/n) for v in c.values() if v)


def step(current, previous):
    # Local graph dynamics: the predecessor edge selects a graph-local rule.
    # No next-state label is stored in memory.
    if current == "S2":
        return "X" if previous == "S1A" else "Y"
    return GRAPH[current][0]


def generate(seed, history):
    rng = random.Random(seed)
    rows = []
    for _ in range(N // 2):
        # History is represented only by the actual predecessor path token.
        prev = "S1A" if history == 0 else "S1B"
        current = "S2"
        nxt = step(current, prev)
        rows.append((current, prev, nxt, history))
    rng.shuffle(rows)
    return rows


def summarize(rows):
    cur = defaultdict(Counter); mem = defaultdict(Counter); hist = defaultdict(Counter)
    for s,m,n,h in rows:
        cur[s][n] += 1; mem[(s,m)][n] += 1; hist[(s,h)][n] += 1
    h0 = entropy(cur["S2"])
    hm = sum(entropy(v) for v in mem.values())/len(mem)
    return {"H_next_given_current": h0, "H_next_given_current_memory": hm,
            "history_distributions": {str(k): dict(v) for k,v in hist.items()}}

if __name__ == "__main__":
    print(summarize(generate(0, 0) + generate(0, 1)))
